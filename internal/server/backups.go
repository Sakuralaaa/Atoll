// Backups: the control server stores policies, the repository settings and run records.
// Agents execute (restic in a container, straight to the bucket) and also own the schedule,
// so nothing here is required for a backup to happen. The scheduler below is a watchdog:
// it pushes policies to agents and asks for a catch-up run when a scheduled run is overdue.

const (
	defaultBackupSchedule = "0 3 * * *"
	defaultBackupPrefix   = "atoll"
)

var defaultBackupKeep = api.BackupKeep{Daily: 7, Weekly: 4, Monthly: 6}

// Tunables (tests shorten them).
var (
	backupTick         = time.Minute
	backupCatchupGrace = 20 * time.Minute // give the agent's own scheduler time first
	backupStaleAfter   = 12 * time.Hour
	backupConfigEvery  = 10 // ticks between periodic config re-pushes
)

// backupDBKinds back up a logical dump taken with the database's own tool.
var backupDBKinds = map[string]bool{"postgres": true, "mysql": true, "mongo": true, "redis": true}

type backupState struct {
	mu          sync.Mutex
	catchupSent map[string]time.Time // service -> scheduled time a catch-up was requested for
	configHash  map[string]string    // node -> hash of the last pushed config
}

var backupStates sync.Map // *Server -> *backupState (keeps Server's struct untouched)

func (s *Server) backups() *backupState {
	v, _ := backupStates.LoadOrStore(s, &backupState{catchupSent: map[string]time.Time{}, configHash: map[string]string{}})
	return v.(*backupState)
}

// serverTimezone is the control server's IANA zone (default for new schedules).
func serverTimezone() string {
	if tz := strings.TrimPrefix(os.Getenv("TZ"), ":"); tz != "" {
		if _, err := cronexpr.LoadLocation(tz); err == nil {
			return tz
		}
	}
	if b, err := os.ReadFile("/etc/timezone"); err == nil {
		if tz := strings.TrimSpace(string(b)); tz != "" {
			if _, err := cronexpr.LoadLocation(tz); err == nil {
				return tz
			}
		}
	}
	if p, err := filepath.EvalSymlinks("/etc/localtime"); err == nil {
		if i := strings.Index(p, "zoneinfo/"); i >= 0 {
			tz := p[i+len("zoneinfo/"):]
			if _, err := cronexpr.LoadLocation(tz); err == nil {
				return tz
			}
		}
	}
	if n := time.Local.String(); n != "Local" && n != "" {
		return n
	}
	return "UTC"
}

// ---------- repository settings ----------

// backupRepo returns the configured repository (ok=false when incomplete).
func (s *Server) backupRepo(ctx context.Context) (api.BackupRepo, bool) {
	get := func(k string) string { v, _ := s.st.GetSetting(ctx, k); return v }
	r := api.BackupRepo{
		Endpoint: get("backup_endpoint"), Bucket: get("backup_bucket"), Prefix: get("backup_prefix"), Region: get("backup_region"),
		AccessKey: get("backup_access_key"), SecretKey: get("backup_secret_key"), Password: get("backup_repo_password"),
	}
	ok := r.Endpoint != "" && r.Bucket != "" && r.AccessKey != "" && r.SecretKey != "" && r.Password != ""
	return r, ok
}

// fillBackupSettings adds the (non-secret) backup fields to a Settings response.
func (s *Server) fillBackupSettings(ctx context.Context, st *api.Settings) {
	r, ok := s.backupRepo(ctx)
	st.BackupEndpoint, st.BackupBucket, st.BackupPrefix, st.BackupRegion = r.Endpoint, r.Bucket, r.Prefix, r.Region
	st.HasBackupCredentials = r.AccessKey != "" && r.SecretKey != ""
	st.HasBackupPassword = r.Password != ""
	st.BackupConfigured = ok
	st.BackupAccessKey, st.BackupSecretKey, st.BackupRepoPassword = "", "", ""
}

var (
	bucketRe       = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$`)
	backupPrefixRe = regexp.MustCompile(`^[A-Za-z0-9._/-]{0,200}$`)
	regionRe       = regexp.MustCompile(`^[a-z0-9-]{0,40}$`)
	endpointRe     = regexp.MustCompile(`^(https?://)?[A-Za-z0-9.-]+(:[0-9]{1,5})?/?$`)
)

// applyBackupSettings validates and stores the backup fields of a PUT /settings body.
// Empty fields keep the stored value (clear the target with DELETE /settings/backup).
// Returns the repository password when it was generated by this call (shown once).
func (s *Server) applyBackupSettings(ctx context.Context, req api.Settings) (generated string, changed bool, err error) {
	req.BackupEndpoint = strings.TrimSpace(req.BackupEndpoint)
	req.BackupBucket = strings.TrimSpace(req.BackupBucket)
	req.BackupPrefix = strings.Trim(strings.TrimSpace(req.BackupPrefix), "/")
	req.BackupRegion = strings.TrimSpace(req.BackupRegion)
	if req.BackupEndpoint != "" && !endpointRe.MatchString(req.BackupEndpoint) {
		return "", false, badRequest("backup_endpoint must be a host or http(s) URL without a path, e.g. https://<account>.r2.cloudflarestorage.com")
	}
	if req.BackupBucket != "" && !bucketRe.MatchString(req.BackupBucket) {
		return "", false, badRequest("invalid backup_bucket %q", req.BackupBucket)
	}
	if !backupPrefixRe.MatchString(req.BackupPrefix) || strings.Contains(req.BackupPrefix, "..") {
		return "", false, badRequest("invalid backup_prefix")
	}
	if !regionRe.MatchString(req.BackupRegion) {
		return "", false, badRequest("invalid backup_region")
	}
	if pw := req.BackupRepoPassword; pw != "" && len(pw) < 12 {
		return "", false, badRequest("backup_repo_password must be at least 12 characters")
	}
	set := map[string]string{}
	if req.BackupEndpoint != "" {
		set["backup_endpoint"] = strings.TrimRight(req.BackupEndpoint, "/")
	}
	if req.BackupBucket != "" {
		set["backup_bucket"] = req.BackupBucket
	}
	if req.BackupPrefix != "" {
		set["backup_prefix"] = req.BackupPrefix
	}
	if req.BackupRegion != "" {
		set["backup_region"] = req.BackupRegion
	}
	if v := strings.TrimSpace(req.BackupAccessKey); v != "" {
		set["backup_access_key"] = v
	}
	if v := strings.TrimSpace(req.BackupSecretKey); v != "" {
		set["backup_secret_key"] = v
	}
	if req.BackupRepoPassword != "" {
		set["backup_repo_password"] = req.BackupRepoPassword
	}
	if len(set) == 0 {
		return "", false, nil
	}
	cur, _ := s.backupRepo(ctx)
	if cur.Prefix == "" && set["backup_prefix"] == "" {
		set["backup_prefix"] = defaultBackupPrefix
	}
	if cur.Password == "" && set["backup_repo_password"] == "" && (cur.Bucket != "" || set["backup_bucket"] != "") {
		generated = randString(40, tokenAlphabet)
		set["backup_repo_password"] = generated
	}
	for k, v := range set {
		if err := s.st.SetSetting(ctx, k, v); err != nil {
			return "", false, err
		}
	}
	keys := make([]string, 0, len(set))
	for k := range set {
		keys = append(keys, k) // names only, never values
	}
	s.st.Audit(ctx, principalFrom(ctx).actor(), "settings.backup", "", map[string]any{"keys": keys, "password_generated": generated != ""})
	return generated, true, nil
}

func (s *Server) handleDeleteBackupSettings(w http.ResponseWriter, r *http.Request) error {
	ctx := r.Context()
	for _, k := range []string{"backup_endpoint", "backup_bucket", "backup_prefix", "backup_region", "backup_access_key", "backup_secret_key"} {
		if _, err := s.st.DB.ExecContext(ctx, `DELETE FROM settings WHERE key=?`, k); err != nil {
			return err
		}
	}
	// the repository password is kept: without it existing snapshots are unreadable
	s.st.Audit(ctx, principalFrom(ctx).actor(), "settings.backup.clear", "", nil)
	s.pushBackupConfigAll(ctx, true)
	st := s.settings(ctx)
	s.fillBackupSettings(ctx, &st)
	writeJSON(w, 200, st)
	return nil
}

// handleBackupPassword reveals the repository password (panel session only, audited).
func (s *Server) handleBackupPassword(w http.ResponseWriter, r *http.Request) error {
	pw, _ := s.st.GetSetting(r.Context(), "backup_repo_password")
	if pw == "" {
		return errf(404, "not_found", "no backup repository password is set")
	}
	s.st.Audit(r.Context(), principalFrom(r.Context()).actor(), "settings.backup.reveal_password", "", nil)
	w.Header().Set("Cache-Control", "no-store")
	writeJSON(w, 200, map[string]string{"password": pw, "repository": func() string { rp, _ := s.backupRepo(r.Context()); return rp.URL() }()})
	return nil
}

// handleBackupTest asks an online agent to open (and if needed initialise) the repository.
// Body fields override stored values so the form can be tested before saving.
func (s *Server) handleBackupTest(w http.ResponseWriter, r *http.Request) error {
	var req struct {
		api.Settings
		ServerID string `json:"server_id"`
	}
	if r.ContentLength != 0 {
		if err := decode(r, &req); err != nil {
			return err
		}
	}
	ctx := r.Context()
	repo, _ := s.backupRepo(ctx)
	over := func(dst *string, v string) {
		if v = strings.TrimSpace(v); v != "" {
			*dst = v
		}
	}
	over(&repo.Endpoint, req.BackupEndpoint)
	over(&repo.Bucket, req.BackupBucket)
	over(&repo.Prefix, req.BackupPrefix)
	over(&repo.Region, req.BackupRegion)
	over(&repo.AccessKey, req.BackupAccessKey)
	over(&repo.SecretKey, req.BackupSecretKey)
	if req.BackupRepoPassword != "" {
		repo.Password = req.BackupRepoPassword
	}
	if repo.Prefix == "" {
		repo.Prefix = defaultBackupPrefix
	}
	if repo.Endpoint == "" || repo.Bucket == "" || repo.AccessKey == "" || repo.SecretKey == "" {
		return badRequest("endpoint, bucket, access key and secret key are required")
	}
	if repo.Password == "" {
		return badRequest("no repository password yet: save the backup settings first (one is generated)")
	}
	node := req.ServerID
	if node == "" {
		nodes, _ := s.st.ListNodes(ctx)
		for _, n := range nodes {
			if s.hub.Online(n.ID) {
				node = n.ID
				break
			}
		}
	}
	if node == "" || !s.hub.Online(node) {
		return errf(409, "server_offline", "no online server to run the check (backups run on the agents)")
	}
	out, err := s.hub.Call(ctx, node, api.MsgBackupTest, repo, 3*time.Minute)
	res := api.BackupTestResult{OK: err == nil, ServerID: node, Message: strings.TrimSpace(out)}
	if err != nil {
		res.Message = strings.TrimPrefix(err.Error(), api.MsgBackupTest+": ")
	}
	writeJSON(w, 200, res)
	return nil
}

// ---------- policies ----------

func (s *Server) defaultPolicy(svc *api.Service) api.BackupPolicy {
	return api.BackupPolicy{ServiceID: svc.ID, Schedule: defaultBackupSchedule, Timezone: serverTimezone(), Keep: defaultBackupKeep, IncludeVolumes: true}
}

// backupParts says what a run of svc snapshots.
func backupParts(svc *api.Service, p api.BackupPolicy) []string {
	var parts []string
	if backupDBKinds[svc.Kind] {
		parts = append(parts, "dump")
		if p.IncludeVolumes && len(svc.Volumes) > 0 {
			parts = append(parts, "volumes")
		}
		return parts
	}
	if len(svc.Volumes) > 0 {
		parts = append(parts, "volumes")
	}
	return parts
}

func (s *Server) policyFor(ctx context.Context, svc *api.Service) (api.BackupPolicy, error) {
	p, err := s.st.GetBackupPolicy(ctx, svc.ID)
	if errors.Is(err, store.ErrNotFound) {
		d := s.defaultPolicy(svc)
		return d, nil
	}
	if err != nil {
		return api.BackupPolicy{}, err
	}
	return *p, nil
}

// decoratePolicy fills the computed fields.
func (s *Server) decoratePolicy(ctx context.Context, svc *api.Service, p *api.BackupPolicy) {
	_, p.RepoConfigured = s.backupRepo(ctx)
	p.Parts = backupParts(svc, *p)
	p.NextRunAt = nil
	if p.Enabled {
		if sc, err := cronexpr.Parse(p.Schedule); err == nil {
			if loc, err := cronexpr.LoadLocation(p.Timezone); err == nil {
				if n := sc.Next(time.Now(), loc); !n.IsZero() {
					n = n.UTC()
					p.NextRunAt = &n
				}
			}
		}
	}
}

func validatePolicy(svc *api.Service, p *api.BackupPolicy) error {
	p.Schedule = strings.TrimSpace(p.Schedule)
	if p.Schedule == "" {
		p.Schedule = defaultBackupSchedule
	}
	sc, err := cronexpr.Parse(p.Schedule)
	if err != nil {
		return badRequest("%v", err)
	}
	if sc.Never() {
		return badRequest("schedule %q never fires", p.Schedule)
	}
	p.Timezone = strings.TrimSpace(p.Timezone)
	if p.Timezone == "" {
		p.Timezone = serverTimezone()
	}
	if _, err := cronexpr.LoadLocation(p.Timezone); err != nil {
		return badRequest("unknown timezone %q", p.Timezone)
	}
	k := p.Keep
	if k.Daily < 0 || k.Weekly < 0 || k.Monthly < 0 || k.Daily > 1000 || k.Weekly > 1000 || k.Monthly > 1000 {
		return badRequest("keep values must be between 0 and 1000")
	}
	if k.Daily+k.Weekly+k.Monthly == 0 {
		return badRequest("retention must keep at least one snapshot (keep.daily, keep.weekly or keep.monthly)")
	}
	if !backupDBKinds[svc.Kind] {
		p.IncludeVolumes = true // volumes are the backup
	}
	if p.Enabled && len(backupParts(svc, *p)) == 0 {
		return badRequest("service %s has no volumes and is not a database template: nothing to back up", svc.Name)
	}
	return nil
}

func (s *Server) handleGetBackupPolicy(w http.ResponseWriter, r *http.Request) error {
	svc, _, err := s.st.GetService(r.Context(), r.PathValue("id"))
	if err != nil {
		return err
	}
	p, err := s.policyFor(r.Context(), svc)
	if err != nil {
		return err
	}
	s.decoratePolicy(r.Context(), svc, &p)
	writeJSON(w, 200, p)
	return nil
}

func (s *Server) handlePutBackupPolicy(w http.ResponseWriter, r *http.Request) error {
	ctx := r.Context()
	svc, _, err := s.st.GetService(ctx, r.PathValue("id"))
	if err != nil {
		return err
	}
	cur, err := s.policyFor(ctx, svc)
	if err != nil {
		return err
	}
	// start from the current policy so partial bodies work
	req := cur
	req.Keep = api.BackupKeep{}
	var raw map[string]json.RawMessage
	if err := decode(r, &raw); err != nil {
		return err
	}
	b, _ := json.Marshal(raw)
	if err := json.Unmarshal(b, &req); err != nil {
		return badRequest("invalid policy: %v", err)
	}
	if _, ok := raw["keep"]; !ok {
		req.Keep = cur.Keep
	}
	req.ServiceID = svc.ID
	if err := validatePolicy(svc, &req); err != nil {
		return err
	}
	if err := s.st.SaveBackupPolicy(ctx, req); err != nil {
		return err
	}
	s.st.Audit(ctx, principalFrom(ctx).actor(), "backup.policy", svc.ID, map[string]any{"enabled": req.Enabled, "schedule": req.Schedule, "timezone": req.Timezone, "keep": req.Keep})
	if node, err := s.serviceNode(ctx, svc); err == nil {
		s.pushBackupConfig(ctx, node, true)
	}
	p, err := s.policyFor(ctx, svc)
	if err != nil {
		return err
	}
	s.decoratePolicy(ctx, svc, &p)
	writeJSON(w, 200, p)
	return nil
}

// targetFor is the agent view of a service's policy.
func targetFor(svc *api.Service, p api.BackupPolicy) api.BackupTarget {
	t := api.BackupTarget{
		ServiceID: svc.ID, ProjectID: svc.ProjectID, Name: svc.Name, Kind: svc.Kind, Volumes: []string{},
		IncludeVolumes: p.IncludeVolumes || !backupDBKinds[svc.Kind], Enabled: p.Enabled,
		Schedule: p.Schedule, Timezone: p.Timezone, Keep: p.Keep,
	}
	for _, v := range svc.Volumes {
		t.Volumes = append(t.Volumes, v.Name)
	}
	return t
}

// backupConfigFor builds the MsgBackupConfig payload of a node.
func (s *Server) backupConfigFor(ctx context.Context, nodeID string) (api.BackupConfigPayload, error) {
	cfg := api.BackupConfigPayload{Targets: []api.BackupTarget{}}
	if repo, ok := s.backupRepo(ctx); ok {
		cfg.Repo = &repo
	}
	rows, err := s.st.ListBackupPolicies(ctx, nodeID)
	if err != nil {
		return cfg, err
	}
	for _, row := range rows {
		svc, _, err := s.st.GetService(ctx, row.ServiceID)
		if err != nil {
			continue
		}
		cfg.Targets = append(cfg.Targets, targetFor(svc, row.BackupPolicy))
	}
	return cfg, nil
}

// pushBackupConfig sends the node its policies; unchanged configs are skipped unless force.
func (s *Server) pushBackupConfig(ctx context.Context, nodeID string, force bool) {
	if !s.hub.Online(nodeID) {
		return
	}
	cfg, err := s.backupConfigFor(ctx, nodeID)
	if err != nil {
		s.log.Warn("backup config", "node", nodeID, "err", err)
		return
	}
	raw, _ := json.Marshal(cfg)
	sum := sha256.Sum256(raw)
	h := hex.EncodeToString(sum[:])
	bs := s.backups()
	bs.mu.Lock()
	same := bs.configHash[nodeID] == h
	if !same || force {
		bs.configHash[nodeID] = h
	}
	bs.mu.Unlock()
	if same && !force {
		return
	}
	s.goBG(func(bg context.Context) {
		if _, err := s.hub.Call(bg, nodeID, api.MsgBackupConfig, cfg, 0); err != nil {
			s.log.Warn("backup config push failed", "node", nodeID, "err", err)
			bs.mu.Lock()
			delete(bs.configHash, nodeID) // retry next tick
			bs.mu.Unlock()
		}
	})
}

func (s *Server) pushBackupConfigAll(ctx context.Context, force bool) {
	nodes, _ := s.st.ListNodes(ctx)
	for _, n := range nodes {
		s.pushBackupConfig(ctx, n.ID, force)
	}
}

// ---------- scheduler (watchdog) ----------

func (s *Server) startBackupScheduler() {
	s.wg.Add(1)
	go func() {
		defer s.wg.Done()
		t := time.NewTicker(backupTick)
		defer t.Stop()
		n := 0
		for {
			select {
			case <-s.bg.Done():
				return
			case now := <-t.C:
				n++
				if n%backupConfigEvery == 1 {
					s.pushBackupConfigAll(s.bg, false)
				}
				s.backupCatchup(s.bg, now)
				if k, _ := s.st.FailStaleBackups(s.bg, backupStaleAfter); k > 0 {
					s.log.Warn("backups without result marked failed", "count", k)
				}
			}
		}
	}()
}

// backupCatchup requests one run for every enabled policy whose last scheduled time passed
// more than backupCatchupGrace ago without a backup record (agent was down, or its local
// schedule was missing). The agent skips it when it did run (Since).
func (s *Server) backupCatchup(ctx context.Context, now time.Time) []string {
	repo, ok := s.backupRepo(ctx)
	if !ok {
		return nil
	}
	rows, err := s.st.ListBackupPolicies(ctx, "")
	if err != nil {
		return nil
	}
	var sent []string
	bs := s.backups()
	for _, row := range rows {
		if !row.Enabled || !s.hub.Online(row.NodeID) {
			continue
		}
		sc, err := cronexpr.Parse(row.Schedule)
		if err != nil {
			continue
		}
		loc, err := cronexpr.LoadLocation(row.Timezone)
		if err != nil {
			continue
		}
		prev := sc.Prev(now, loc)
		if prev.IsZero() || now.Sub(prev) < backupCatchupGrace {
			continue
		}
		// a policy saved after that fire time has nothing to catch up
		if row.UpdatedAt != nil && row.UpdatedAt.After(prev) {
			continue
		}
		if _, err := s.st.LatestBackupSince(ctx, row.ServiceID, prev); err == nil {
			continue
		}
		bs.mu.Lock()
		already := bs.catchupSent[row.ServiceID].Equal(prev)
		if !already {
			bs.catchupSent[row.ServiceID] = prev
		}
		bs.mu.Unlock()
		if already {
			continue
		}
		svc, _, err := s.st.GetService(ctx, row.ServiceID)
		if err != nil {
			continue
		}
		since := prev.UTC()
		p := api.BackupRunPayload{BackupID: newID("bak"), Trigger: "catchup", Target: targetFor(svc, row.BackupPolicy), Repo: repo, Since: &since}
		s.hub.Fire(row.NodeID, api.MsgBackupRun, p)
		s.log.Info("backup catch-up requested", "service", svc.ID, "scheduled", since)
		sent = append(sent, svc.ID)
	}
	return sent
}

// ---------- runs ----------

func (s *Server) handleRunBackup(w http.ResponseWriter, r *http.Request) error {
	ctx := r.Context()
	svc, _, err := s.st.GetService(ctx, r.PathValue("id"))
	if err != nil {
		return err
	}
	b, err := s.runBackupNow(ctx, svc, principalFrom(ctx).actor())
	if err != nil {
		return err
	}
	writeJSON(w, 202, b)
	return nil
}

func (s *Server) runBackupNow(ctx context.Context, svc *api.Service, actor string) (*api.Backup, error) {
	repo, ok := s.backupRepo(ctx)
	if !ok {
		return nil, errf(409, "backup_not_configured", "configure a backup target in Settings → 备份存储 first")
	}
	p, err := s.policyFor(ctx, svc)
	if err != nil {
		return nil, err
	}
	if len(backupParts(svc, p)) == 0 {
		return nil, badRequest("service %s has no volumes and is not a database template: nothing to back up", svc.Name)
	}
	node, err := s.serviceNode(ctx, svc)
	if err != nil {
		return nil, err
	}
	if !s.hub.Online(node) {
		return nil, errf(409, "server_offline", "%v", ErrNodeOffline)
	}
	b := api.Backup{ID: newID("bak"), ServiceID: svc.ID, ServerID: node, Trigger: "manual", Status: "running",
		Snapshots: []api.BackupSnapshot{}, StartedAt: time.Now().UTC()}
	if err := s.st.SaveBackup(ctx, b); err != nil {
		return nil, err
	}
	payload := api.BackupRunPayload{BackupID: b.ID, Trigger: "manual", Target: targetFor(svc, p), Repo: repo}
	if _, err := s.hub.Call(ctx, node, api.MsgBackupRun, payload, 0); err != nil {
		now := time.Now().UTC()
		b.Status, b.Error, b.FinishedAt = "failed", err.Error(), &now
		s.st.SaveBackup(ctx, b)
		return nil, errf(502, "agent_error", "%v", err)
	}
	s.st.Audit(ctx, actor, "backup.run", svc.ID, map[string]string{"backup": b.ID})
	s.publish("backup", b)
	return &b, nil
}

// handleBackupEvent records an agent's backup progress / result.
func (s *Server) handleBackupEvent(ctx context.Context, nodeID string, ev api.BackupEvent) {
	if ev.BackupID == "" || ev.ServiceID == "" {
		return
	}
	b := api.Backup{ID: ev.BackupID, ServiceID: ev.ServiceID, ServerID: nodeID, Trigger: ev.Trigger, Status: ev.Status,
		Snapshots: ev.Snapshots, Bytes: ev.Bytes, Added: ev.Added, DurationMs: ev.DurationMs, Error: ev.Error,
		Warnings: ev.Warnings, StartedAt: ev.StartedAt, FinishedAt: ev.FinishedAt}
	if old, err := s.st.GetBackup(ctx, ev.BackupID); err == nil && old.ID == ev.BackupID {
		b.Trigger = old.Trigger
		if b.StartedAt.IsZero() {
			b.StartedAt = old.StartedAt
		}
	}
	if b.Trigger == "" {
		b.Trigger = "schedule"
	}
	if b.StartedAt.IsZero() {
		b.StartedAt = time.Now().UTC()
	}
	if err := s.st.SaveBackup(ctx, b); err != nil {
		if !strings.Contains(err.Error(), "FOREIGN KEY") {
			s.log.Warn("save backup", "backup", b.ID, "err", err)
		}
		return
	}
	if err := s.st.MarkSnapshotsPruned(ctx, ev.ServiceID, ev.Pruned); err != nil {
		s.log.Warn("mark pruned", "service", ev.ServiceID, "err", err)
	}
	if b.Status == "failed" {
		s.log.Warn("backup failed", "service", b.ServiceID, "backup", b.ID, "err", b.Error)
	}
	if cur, err := s.st.GetBackup(ctx, b.ID); err == nil {
		s.publish("backup", cur)
	}
}

